/// A2B at the fixed-point width leaves bits `33..64` clear, for every payload the width admits.
///
/// `FixedPointPrecision::new(32, 16)` is this repo's default, and the plan's §2.4 attaches
/// `ell = k + 1 = 33` to it: `truncpr` already shifts a signed `k`-bit value into `[0, 2^k]`, a
/// closed interval whose upper endpoint needs the 33rd bit, and an unrescaled sum of two shifted
/// operands sets that bit outright.
///
/// The assertion is stronger than "the low 33 bits are right". A2B always emits 64 bits, so a
/// caller narrowing to 33 is relying on the high 31 being clear — and a conversion that got the
/// payload right while leaving rubbish above it would pass a low-bits-only check and then lose the
/// value the moment anyone fed it to B2A. Both halves are checked here.
#[tokio::test]
async fn a2b_at_the_fixed_point_width_leaves_the_high_bits_clear() {
    setup_tracing();

    let (n_parties, t) = (10usize, 3usize);
    let precision = fixed_point_precision();
    let ell = fixed_point_width();
    assert_eq!((precision.k(), precision.f()), (32, 16), "the repo default");
    assert_eq!(ell, 33, "ell = k + 1 at the default precision");

    let corpus = fixed_point_corpus();
    let values: Vec<F> = corpus.iter().map(|(_, v)| F::from(*v)).collect();

    let harness = ConvHarness::new(n_parties, t, 211);
    let mut rng = StdRng::seed_from_u64(2_013);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &values, &mut rng);
    let edabits = deal_edabits(n_parties, t, values.len(), &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);

    let results = harness.a2b(1, inputs, edabits, triples).await;
    assert_a2b_matches("fixed-point-width", &values, &results, n_parties, t);

    let width = field_bit_width::<F>();
    for (index, (label, payload)) in corpus.iter().enumerate() {
        let got: Vec<bool> = (0..width)
            .map(|bit| {
                let column: Vec<GfShare<K>> =
                    results.iter().map(|r| r[index][bit].clone()).collect();
                recover_bit(&column, n_parties, t)
            })
            .collect();
        assert!(
            got[ell..].iter().all(|bit| !bit),
            "{label}: a payload below 2^{ell} must leave every bit from {ell} up clear"
        );
        assert_eq!(
            as_integer(&got[0..ell]),
            *payload as u128,
            "{label}: the low {ell} bits are not the payload"
        );
    }
}

/// The standing negative result of plan §2.4, made concrete: an **unshifted** negative
/// fixed-point value is not 33 bits wide, and no amount of narrowing makes it so.
///
/// `mpc/src/common/types` encodes `-v` as `p - v`, so `-1` is `0xFFFF_FFFF_0000_0000` — a 64-bit
/// number whose low 32 bits are clear. Narrowing A2B's output to the fixed-point width would
/// silently read it as zero. The free `+2^(k-1)` shift that `truncpr.rs:192` already applies is
/// what makes the value narrow, and this test pins both halves of that: the unshifted form
/// overflows the width, the shifted form does not.
///
/// It also pins the *cost* half of the same negative result. A2B's preprocessing does not shrink
/// at `ell = 33`: the mask has to be uniform on `[0, p)` whatever the payload's width, so the
/// edaBit stays 64 daBits and the triple bound stays the full-width one. The blueprint's cost
/// tables quoted "ell = 33 is cheaper"; §2.4 corrects that to "identical preprocessing, only the
/// circuit narrows, and only against a certified bit width".
#[tokio::test]
async fn a2b_does_not_narrow_an_unshifted_negative_fixed_point_value() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    let ell = fixed_point_width();
    let width = field_bit_width::<F>();

    // `-1` unshifted, and `-1` shifted: `2^31 - 1`.
    let minus_one = F::from(0u64) - F::from(1u64);
    let shifted = F::from(shift_to_unsigned(-1));
    let values = vec![minus_one, shifted];

    let harness = ConvHarness::new(n_parties, t, 212);
    let mut rng = StdRng::seed_from_u64(2_014);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &values, &mut rng);
    let edabits = deal_edabits(n_parties, t, values.len(), &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);

    // The preprocessing is full width on both, and is drawn before either value is known: there
    // is no `ell` parameter anywhere on this path, which is the cost half of §2.4.
    assert_eq!(
        per_conversion, PARALLEL_AND_BOUND,
        "the triple bound is the full-width one regardless of the payload width"
    );
    for party_edabits in &edabits {
        assert_eq!(
            party_edabits[0].bits.len(),
            width,
            "the mask stays 64 daBits wide at ell = 33"
        );
    }

    let results = harness.a2b(1, inputs, edabits, triples).await;
    assert_a2b_matches("unshifted-negative", &values, &results, n_parties, t);

    let recover_all = |index: usize| -> Vec<bool> {
        (0..width)
            .map(|bit| {
                let column: Vec<GfShare<K>> =
                    results.iter().map(|r| r[index][bit].clone()).collect();
                recover_bit(&column, n_parties, t)
            })
            .collect()
    };

    let unshifted = recover_all(0);
    assert!(
        unshifted[ell..].iter().any(|bit| *bit),
        "p - 1 must overflow the fixed-point width"
    );
    // And what narrowing it *would* produce is the sharper half of the hazard: not an obviously
    // broken value, but `2^32` — the headroom bit alone. Read back as a shifted fixed-point
    // number that is `2^32 - 2^31 = +2^31`, one past the largest representable positive. So `-1`
    // narrows to the extreme *opposite* end of the range, with nothing anywhere to object.
    assert_eq!(
        as_integer(&unshifted[0..ell]),
        1u128 << 32,
        "p - 1 narrows to the headroom bit alone"
    );
    assert_ne!(
        as_integer(&unshifted[0..ell]),
        shift_to_unsigned(-1) as u128,
        "the narrowed unshifted form must not coincidentally be the shifted one"
    );

    let after_shift = recover_all(1);
    assert!(
        after_shift[ell..].iter().all(|bit| !bit),
        "the shifted form fits the width"
    );
    assert_eq!(
        as_integer(&after_shift[0..ell]),
        shift_to_unsigned(-1) as u128,
        "the shifted form narrows to 2^31 - 1"
    );
}

/// `b2a(narrow_to_33(a2b([x]))) == [x]` over the whole fixed-point corpus.
///
/// The round trip a fixed-point mixed circuit actually performs: decompose, operate on 33 bits,
/// recompose. It is exact because of the test above — A2B leaves bits `33..64` clear for every
/// in-range payload — and `ell = 33` is comfortably inside B2A's `max_width::<F>() = 63` bound, so
/// it takes the checked entry point rather than the full-width one.
///
/// B2A's cost *does* fall linearly with `ell` (§2.4), and that is pinned by construction: the
/// conversion is handed exactly `33 * values` daBits and `B2ANode::b2a` rejects any other count
/// outright, so completing at all is the assertion.
#[tokio::test]
async fn a2b_then_b2a_round_trips_at_the_fixed_point_width() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    let ell = fixed_point_width();
    let corpus = fixed_point_corpus();
    let values: Vec<F> = corpus.iter().map(|(_, v)| F::from(*v)).collect();

    let harness = ConvHarness::new(n_parties, t, 213);
    let mut rng = StdRng::seed_from_u64(2_015);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &values, &mut rng);
    let edabits = deal_edabits(n_parties, t, values.len(), &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);
    let dabits = deal_dabits(n_parties, t, ell * values.len(), &mut rng);

    let bits = harness.a2b(1, inputs, edabits, triples).await;
    assert_a2b_matches("fixed-point-roundtrip", &values, &bits, n_parties, t);

    let narrowed: Vec<Vec<Vec<GfShare<K>>>> = bits
        .iter()
        .map(|per_value| {
            per_value
                .iter()
                .map(|value_bits| value_bits[0..ell].to_vec())
                .collect()
        })
        .collect();

    let back = harness.b2a(1, narrowed, dabits, false).await;
    for (index, (label, payload)) in corpus.iter().enumerate() {
        let column: Vec<RobustShare<F>> = back.iter().map(|per| per[index].clone()).collect();
        assert_eq!(
            recover_field(&column, n_parties, t),
            F::from(*payload),
            "{label}: the fixed-point round trip lost the value"
        );
    }
}

// -------------------------------------------------------------------------------------------
// The depth-7 circuit against the depth-13 one it replaces
// -------------------------------------------------------------------------------------------

/// The parallel offset adder computes exactly the function the serial chain did, on every input
/// that matters.
///
/// The two circuits differ in more than their layering. The serial chain reduces on `c1 XOR c2`,
/// where `c1` is the carry out of `y + r` and `c2` the carry out of adding `d` to the *truncated*
/// sum; the parallel form never forms `c1` and reduces on `c2` alone, where that `c2` is the carry
/// out of a different addition, `(y + d) + r`. That the two agree is a theorem about `p`, not an
/// algebraic identity, so it is worth a sweep rather than an argument.
///
/// The sweep is exhaustive over the cross product of the boundary corpus with itself — every
/// `(x, r)` pair on a carry boundary of either form, including the `2^32 - 1` neighbourhood where
/// the serial chain's `c1` is the deciding bit — plus a uniform tail. Both models are checked
/// against `(y + r) mod p` as well as against each other, so a shared misreading of the algebra
/// cannot pass.
#[test]
fn the_parallel_offset_adder_agrees_with_the_serial_chain_it_replaced() {
    let mut corpus: Vec<u64> = boundary_values()
        .iter()
        .map(|(_, value)| {
            let mut repr = [0u8; 8];
            repr.copy_from_slice(&value.into_bigint().to_bytes_le()[0..8]);
            u64::from_le_bytes(repr)
        })
        .collect();
    // The `2^32 - 1` neighbourhood again, from the mask's side this time, plus the extremes of
    // the admissible range for `r`.
    corpus.extend_from_slice(&[(1u64 << 32) - 2, (1u64 << 32) - 1, 1u64 << 32, P - 1, P / 2]);

    let mut rng = StdRng::seed_from_u64(2_016);
    let mut extra: Vec<u64> = Vec::with_capacity(64);
    while extra.len() < 64 {
        let candidate: u64 = rng.gen();
        if candidate < P {
            extra.push(candidate);
        }
    }
    corpus.extend_from_slice(&extra);

    let mut checked = 0usize;
    for &x in &corpus {
        assert!(x < P, "the corpus must be canonical");
        for &r in &corpus {
            // `y = (x - r) mod p`, exactly what the mask opening publishes. Written as
            // `p - (r - x)` rather than `x + p - r`: both are the same residue, but the latter
            // overflows `u64` for a large `x`.
            let y = if x >= r { x - r } else { P - (r - x) };
            let serial = serial_offset_adder(y, r);
            let parallel = parallel_offset_adder(y, r);
            assert_eq!(
                serial, parallel,
                "the two circuits disagree at y = {y}, r = {r}"
            );
            assert_eq!(
                parallel, x,
                "the conversion is not the identity at y = {y}, r = {r}"
            );
            checked += 1;
        }
    }
    assert!(checked > 6_000, "the sweep collapsed to {checked} pairs");
}

/// The **protocol's** output is the serial chain's output, on masks chosen to pin each branch.
///
/// The sweep above compares two clear-text models. This compares the model that describes the
/// replaced circuit against what the deployed one actually returns over the wire — the assertion
/// that closes the loop, since a model can agree with a theorem and still fail to describe the
/// code. Masks are chosen rather than sampled, because the row where the serial chain's `c1` is
/// set has probability `2^-32` under a uniform mask.
#[tokio::test]
async fn a2b_output_matches_the_serial_chain_on_chosen_masks() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    let width = field_bit_width::<F>();

    // (x, r), one per row of the branch table in `a2b_covers_every_carry_branch`, plus the
    // degenerate `r = 0` and `x = r` cases.
    let cases: Vec<(u64, u64)> = vec![
        (1u64 << 40, 0),
        (1u64 << 40, 1),
        (P - 1, P - 1),
        (5, P - 1),
        ((1u64 << 32) - 2, P - 1),
        ((1u64 << 32) - 1, P - 1),
        (P - 2, P - 1),
        (0, 1),
        (0xDEAD_BEEF_CAFE_F00D % P, 0x0123_4567_89AB_CDEF),
    ];

    let values: Vec<F> = cases.iter().map(|(x, _)| F::from(*x)).collect();
    let masks: Vec<u64> = cases.iter().map(|(_, r)| *r).collect();

    let harness = ConvHarness::new(n_parties, t, 214);
    let mut rng = StdRng::seed_from_u64(2_017);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &values, &mut rng);
    let edabits = deal_edabits_from(n_parties, t, &masks, &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);

    let results = harness.a2b(1, inputs, edabits, triples).await;

    for (index, (x, r)) in cases.iter().enumerate() {
        let y = if x >= r { x - r } else { P - (r - x) };
        let want = bits_le(serial_offset_adder(y, *r), width);
        let got: Vec<bool> = (0..width)
            .map(|bit| {
                let column: Vec<GfShare<K>> =
                    results.iter().map(|res| res[index][bit].clone()).collect();
                recover_bit(&column, n_parties, t)
            })
            .collect();
        assert_eq!(
            got, want,
            "the protocol and the replaced serial chain disagree at x = {x}, r = {r}"
        );
        // And the serial chain was itself right, so this is not two wrongs agreeing.
        assert_eq!(
            as_integer(&want),
            *x as u128,
            "serial model wrong at x = {x}"
        );
    }
}

/// The replacement's headline trade, pinned as a pair of netlists rather than as a comment:
/// **+11% ANDs on the sizing bound for -46% depth**.
///
/// Both netlists are built from the same public `Builder` and prefix primitives, so this is a
/// like-for-like comparison after the same constant folding and backward-liveness pass. The serial
/// chain's bound is a *realisable* plan — an all-ones `y` is admissible there — while the parallel
/// one's is analytic, because an all-ones `y` would make `Y = y + d` wrap and
/// `FieldA2BCircuit::new` rejects it. That asymmetry is the reason the two numbers are quoted from
/// different kinds of witness, and it is why `max_and_count()` is a bound rather than a maximum:
/// the largest count an admissible `y` reaches is 693, not 695.
///
/// Message rounds follow from the depth: `2 + layers * rounds_per_opening`, the leading 2 being
/// the mask opening's own `BatchRecon` round trip. So 13 layers was 28 batched rounds and 7 is
/// 16. `OpeningPolicy::Direct` governs the AND layers only — the mask opening stays batched — so
/// the same 7 layers is **9**, not the plan's 8.
#[test]
fn the_parallel_circuit_is_depth_7_where_the_serial_chain_was_13() {
    let width = field_bit_width::<F>();
    assert_eq!(width, 64);

    let serial = serial_a2b_netlist(width);
    assert_eq!(
        (serial.and_count(), serial.layers()),
        (SERIAL_AND_BOUND, SERIAL_DEPTH),
        "the replaced serial chain is 626 ANDs at depth 13"
    );

    let parallel_ands = FieldA2BCircuit::<F>::max_and_count().unwrap();
    let parallel_depth = FieldA2BCircuit::<F>::max_layers().unwrap();
    assert_eq!(
        (parallel_ands, parallel_depth),
        (PARALLEL_AND_BOUND, PARALLEL_DEPTH),
        "the landed parallel offset adder is 695 ANDs at depth 7"
    );

    // The trade, in the direction the plan claims it: dearer per conversion, shallower.
    assert!(parallel_ands > SERIAL_AND_BOUND);
    assert!(parallel_depth < SERIAL_DEPTH);
    assert_eq!(
        A2BNode::<F, K>::gf_triples_per_conversion().unwrap(),
        parallel_ands,
        "the preprocessing sizer must be handed the bound, not the average"
    );
    assert_eq!(
        A2BNode::<F, K>::max_and_layers().unwrap(),
        parallel_depth,
        "the wave count must be the circuit's depth"
    );
}
