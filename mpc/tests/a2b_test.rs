/// A short edaBit is refused, not silently zero-extended.
///
/// A2B masks the whole canonical range, so an edaBit narrower than the field width cannot mask it;
/// a short one is also, by construction, one the `r < p` filter was never applied to, and with
/// `r >= p` the adder's "at most one subtraction of `p`" argument fails and the output is simply
/// wrong. The refusal happens before any message is sent.
#[tokio::test]
async fn a2b_refuses_a_short_edabit() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    let harness = ConvHarness::new(n_parties, t, 208);
    let mut rng = StdRng::seed_from_u64(2_009);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &[F::from(7u64)], &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion, &mut rng);
    // `compose` rather than `compose_full_width`: a narrow edaBit, which is the only kind that can
    // be built without an opened overflow bit.
    let narrow = deal_dabits(n_parties, t, max_width::<F>(), &mut rng);

    let mut node = harness.a2b[0].clone();
    let edabit = EdaBit::compose(&narrow[0], max_width::<F>()).unwrap();
    let err = node
        .init(
            harness.a2b_session(1),
            inputs[0].clone(),
            vec![edabit],
            triples[0].clone(),
            TIMEOUT,
            harness.network[0].clone(),
        )
        .await
        .expect_err("a short edabit must be refused");
    assert!(
        format!("{err:?}").contains("EdaBitWidthMismatch"),
        "unexpected error: {err:?}"
    );
}

/// Every branch of the conditional reduction, driven by a **chosen** mask rather than a sampled
/// one.
///
/// With `y = (x - r) mod p`, `A = y + r` over the integers and `d = 2^64 - p = 2^32 - 1`, the
/// parallel offset adder's single carry is determined by `x` and `r` alone. `c2` is the carry out
/// of `(y + d) + r`, and `c2 = 1` iff `A >= p`:
///
/// | case | `A` | `c2` | selected | first adder wraps |
/// |---|---|---|---|---|
/// | `x >= r` | `x < p` | 0 | `t1 = A = x` | no |
/// | `x < r`, `x < 2^32 - 1` | `x + p < 2^64` | 1 | `t2 = A - p = x` | no |
/// | `x < r`, `x >= 2^32 - 1` | `x + p >= 2^64` | 1 | `t2 = A - p = x` | **yes** |
///
/// The last column is what used to be the serial chain's `c1`. That carry is no longer formed —
/// `Builder::finish` deletes its whole cone — but the row is still the interesting one, because it
/// is exactly where `t1` is the wrapped, meaningless `A - 2^64` and the multiplexer must not pick
/// it. Sampling `r` at random reaches the three rows with probability roughly `1/2`, `1/2` and
/// `2^-32`, so the last is pinned here explicitly rather than left to luck.
#[tokio::test]
async fn a2b_covers_every_carry_branch() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    // (value, mask, which row of the table above)
    let cases: Vec<(u64, u64, &str)> = vec![
        (1u64 << 40, 1, "x >= r, no reduction"),
        (P - 1, P - 1, "x == r, y == 0"),
        (5, P - 1, "x < r, x < 2^32 - 1: c1 = 0, c2 = 1"),
        (
            (1u64 << 32) - 2,
            P - 1,
            "x < r, one below the c1 boundary: c1 = 0, c2 = 1",
        ),
        (
            (1u64 << 32) - 1,
            P - 1,
            "x < r, exactly at the c1 boundary: c1 = 1, c2 = 0",
        ),
        (1u64 << 40, P - 1, "x < r, x >= 2^32 - 1: c1 = 1, c2 = 0"),
        (P - 2, P - 1, "x < r, largest possible x: c1 = 1, c2 = 0"),
    ];

    let values: Vec<F> = cases.iter().map(|(x, _, _)| F::from(*x)).collect();
    let masks: Vec<u64> = cases.iter().map(|(_, r, _)| *r).collect();

    let harness = ConvHarness::new(n_parties, t, 209);
    let mut rng = StdRng::seed_from_u64(2_010);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &values, &mut rng);
    let edabits = deal_edabits_from(n_parties, t, &masks, &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);

    let results = harness.a2b(1, inputs, edabits, triples).await;
    assert_a2b_matches("carry-branches", &values, &results, n_parties, t);
}

