/// `b2a_full_width_unchecked(a2b([x])) == [x]` for every `x in F`.
///
/// This is the one caller that can discharge `b2a_full_width_unchecked`'s precondition: A2B emits
/// the bits of the canonical representative, which is by definition below `p`, so the 64-bit
/// recomposition is faithful. Any other 64-bit caller silently gets `x mod p` for the `2^32 - 1`
/// payloads in `[p, 2^64)`, which is exactly why the unchecked entry point is named as it is.
#[tokio::test]
async fn a2b_then_b2a_full_width_round_trips() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    let width = field_bit_width::<F>();
    // Includes `p - 1`, whose 64-bit recomposition is one below the modulus: the exact case that
    // makes the full-width variant unsafe for any *other* caller.
    let values = vec![
        F::from(0u64),
        F::from(1u64),
        F::from(1u64 << 32),
        F::from(1u64 << 63),
        F::from(0u64) - F::from(1u64),
    ];

    let harness = ConvHarness::new(n_parties, t, 206);
    let mut rng = StdRng::seed_from_u64(2_007);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, &values, &mut rng);
    let edabits = deal_edabits(n_parties, t, values.len(), &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);
    let dabits = deal_dabits(n_parties, t, width * values.len(), &mut rng);

    let bits = harness.a2b(1, inputs, edabits, triples).await;
    assert_a2b_matches("roundtrip-forward", &values, &bits, n_parties, t);

    let back = harness.b2a(1, bits, dabits, true).await;
    for (index, want) in values.iter().enumerate() {
        let column: Vec<RobustShare<F>> = back
            .iter()
            .map(|per_value| per_value[index].clone())
            .collect();
        assert_eq!(
            recover_field(&column, n_parties, t),
            *want,
            "round trip lost value {index}"
        );
    }
}

/// `a2b(b2a(bits)) == bits` for random bit vectors at the B2A width bound.
///
/// The other direction of the round trip, and the one that pins the *widths* against each other:
/// B2A accepts at most `max_width::<F>() = 63` bits while A2B always emits 64, so the identity
/// holds only if A2B's extra top bit is zero — which it is, because `sum_{i<63} 2^i b_i < 2^63 < p`
/// cannot reach bit 63 of the canonical representative.
#[tokio::test]
async fn b2a_then_a2b_round_trips() {
    setup_tracing();

    let (n_parties, t) = (4usize, 1usize);
    let ell = max_width::<F>();
    assert_eq!(ell, 63);
    let values = 3usize;

    let harness = ConvHarness::new(n_parties, t, 207);
    let mut rng = StdRng::seed_from_u64(2_008);

    // Two random vectors and one all-ones vector: `2^63 - 1` is the largest value B2A can carry,
    // and the one a width-by-one overshoot gets wrong.
    let clear: Vec<Vec<bool>> = (0..values)
        .map(|index| {
            (0..ell)
                .map(|_| if index == values - 1 { true } else { rng.gen() })
                .collect()
        })
        .collect();

    let mut per_party_bits: Vec<Vec<Vec<GfShare<K>>>> = vec![Vec::new(); n_parties];
    for value_bits in &clear {
        let columns = deal_bits(n_parties, t, value_bits, &mut rng);
        for party in 0..n_parties {
            per_party_bits[party].push(columns[party].clone());
        }
    }

    let dabits = deal_dabits(n_parties, t, ell * values, &mut rng);
    let arithmetic = harness.b2a(1, per_party_bits, dabits, false).await;

    let mut recovered = Vec::with_capacity(values);
    for index in 0..values {
        let column: Vec<RobustShare<F>> = arithmetic
            .iter()
            .map(|per_value| per_value[index].clone())
            .collect();
        let value = recover_field(&column, n_parties, t);
        assert_eq!(
            value,
            F::from(recompose_u128(&clear[index]) as u64),
            "B2A recomposed value {index} wrongly"
        );
        recovered.push(value);
    }

    // Feed the arithmetic shares B2A produced straight back in, without re-dealing them.
    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let edabits = deal_edabits(n_parties, t, values, &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values, &mut rng);
    let inputs: Vec<Vec<RobustShare<F>>> = arithmetic;

    let bits = harness.a2b(2, inputs, edabits, triples).await;
    assert_a2b_matches("roundtrip-reverse", &recovered, &bits, n_parties, t);

    for (index, want) in clear.iter().enumerate() {
        for bit in 0..ell {
            let column: Vec<GfShare<K>> = bits.iter().map(|r| r[index][bit].clone()).collect();
            assert_eq!(
                recover_bit(&column, n_parties, t),
                want[bit],
                "value {index} bit {bit} did not survive the round trip"
            );
        }
        let top: Vec<GfShare<K>> = bits.iter().map(|r| r[index][ell].clone()).collect();
        assert!(
            !recover_bit(&top, n_parties, t),
            "a value below 2^63 must leave A2B's top bit clear"
        );
    }
}

