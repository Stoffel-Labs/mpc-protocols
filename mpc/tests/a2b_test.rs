//! Standalone end-to-end tests of arithmetic-to-binary conversion (blueprint §7.2, tests 7-9).
//!
//! Tier A: `A2BNode` and `B2ANode` are driven directly, with a hand-rolled receiver task per party
//! demuxing `WrappedMessage` exactly as `gf_mul_test.rs` does — no `HoneyBadgerMPCNode` in the
//! loop. `a2b_node_test.rs` covers the same conversions through the node dispatcher.
//!
//! What these tests pin is the arithmetic of the *exact*, full-range conversion:
//!
//! * every value of `F` converts, including the ones that sit on a carry boundary of either of the
//!   adder's two 64-bit additions or on the boundary of the conditional reduction by `p`;
//! * the output is the canonical representative in `[0, p)`, never two's complement;
//! * `b2a_full_width_unchecked ∘ a2b` and `a2b ∘ b2a` are both the identity, the first for every
//!   `x in F` and the second for every bit vector up to `max_width::<F>()`.
//!
//! The conversion preprocessing is dealt honestly by [`utils::a2b_utils`] rather than generated by
//! `PrssDaBitNode`; the reasoning is in that file's header. Nothing here therefore says anything
//! about daBit *generation* — these are tests of the conversion. Generation is covered by
//! `prss_dabit_test.rs` and the `r < p` filter by `edabit_filter_test.rs`.

