/// Generous: these conversions run 7 AND layers plus an arithmetic opening over a `FakeNetwork`
/// shared with every other test in the binary, and a timeout that fires is indistinguishable from
/// a protocol that never completes.
const TIMEOUT: Duration = Duration::from_secs(120);

/// One party's pair of conversion nodes plus the receiver task feeding them.
///
/// `A2BNode` and `B2ANode` are `Clone` over `Arc`-shared stores, so the clone the receiver task
/// owns and the clone a conversion driver owns are the same node.
struct ConvHarness {
    n_parties: usize,
    instance_id: u32,
    network: Vec<Arc<FakeNetwork>>,
    a2b: Vec<A2BNode<F, K>>,
    b2a: Vec<B2ANode<F, K>>,
    /// Held so the receiver tasks outlive the test body: dropping a `JoinSet` aborts its tasks.
    _tasks: JoinSet<()>,
}

impl ConvHarness {
    fn new(n_parties: usize, t: usize, instance_id: u32) -> Self {
        let config = FakeNetworkConfig::new(500);
        let (inner, mut receivers, _) = FakeInnerNetwork::new(n_parties, None, config);
        let network: Vec<Arc<FakeNetwork>> = (0..n_parties)
            .map(|id| Arc::new(FakeNetwork::new(id, inner.clone())))
            .collect();

        let a2b: Vec<A2BNode<F, K>> = (0..n_parties)
            .map(|id| A2BNode::<F, K>::new(id, n_parties, t).unwrap())
            .collect();
        let b2a: Vec<B2ANode<F, K>> = (0..n_parties)
            .map(|id| B2ANode::<F, K>::new(id, n_parties, t).unwrap())
            .collect();

        let mut tasks = JoinSet::new();
        for id in 0..n_parties {
            let mut a2b_node = a2b[id].clone();
            let mut b2a_node = b2a[id].clone();
            let net = network[id].clone();
            let inbox: Vec<(SenderId, tokio::sync::mpsc::Receiver<Vec<u8>>)> =
                std::mem::take(&mut receivers[id])
                    .into_iter()
                    .enumerate()
                    .map(|(sender, rx)| (SenderId::Node(sender), rx))
                    .collect();
            let mut merged = fan_in_inboxes(inbox);

            tasks.spawn(async move {
                while let Some((_sender, bytes)) = merged.recv().await {
                    let wrapped: WrappedMessage = match bincode::deserialize(&bytes) {
                        Ok(wrapped) => wrapped,
                        Err(e) => {
                            warn!(?e, "undeserializable message");
                            continue;
                        }
                    };
                    // Exactly the arms `HoneyBadgerMPCNode::process` routes for these two tags,
                    // each `process` immediately followed by its matching drain (C10): nothing
                    // else moves a finished reconstruction out of the batch-recon store, so a
                    // missing drain is a silent hang rather than an error.
                    match wrapped {
                        WrappedMessage::BatchRecon(msg) => {
                            match msg.session_id.calling_protocol() {
                                Some(ProtocolType::A2B) => {
                                    if let Err(e) =
                                        a2b_node.open.process(msg, Arc::clone(&net)).await
                                    {
                                        warn!(?e, "A2B mask opening");
                                    }
                                    if let Err(e) = a2b_node.drain_open_output().await {
                                        warn!(?e, "A2B mask-opening drain");
                                    }
                                }
                                other => panic!("unexpected BatchRecon caller {other:?}"),
                            }
                        }
                        WrappedMessage::GfBatchRecon(msg) => {
                            match msg.session_id.calling_protocol() {
                                Some(ProtocolType::A2BGfMul) => {
                                    if let Err(e) = a2b_node
                                        .gf_mul
                                        .batch_recon
                                        .process(msg, Arc::clone(&net))
                                        .await
                                    {
                                        warn!(?e, "A2B AND-layer reconstruction");
                                    }
                                    if let Err(e) = a2b_node.drain_gf_mul_output().await {
                                        warn!(?e, "A2B AND-layer drain");
                                    }
                                }
                                Some(ProtocolType::B2A) => {
                                    if let Err(e) =
                                        b2a_node.gf_open.process(msg, Arc::clone(&net)).await
                                    {
                                        warn!(?e, "B2A opening");
                                    }
                                    if let Err(e) = b2a_node.drain_gf_open_output().await {
                                        warn!(?e, "B2A opening drain");
                                    }
                                }
                                other => panic!("unexpected GfBatchRecon caller {other:?}"),
                            }
                        }
                        WrappedMessage::GfMult(msg) => match msg.session_id.calling_protocol() {
                            Some(ProtocolType::A2BGfMul) => {
                                if let Err(e) = a2b_node
                                    .gf_mul
                                    .process(msg.sender, msg.session_id, msg.payload)
                                    .await
                                {
                                    warn!(?e, "A2B AND-layer direct open");
                                }
                            }
                            other => panic!("unexpected GfMult caller {other:?}"),
                        },
                        other => panic!("unexpected wrapped message {other:?}"),
                    }
                }
            });
        }

        Self {
            n_parties,
            instance_id,
            network,
            a2b,
            b2a,
            _tasks: tasks,
        }
    }

    fn a2b_session(&self, exec: u64) -> SessionId {
        SessionId::new(
            ProtocolType::A2B,
            SessionId::pack_slot(exec, 0, 0),
            self.instance_id,
        )
    }

    fn b2a_session(&self, exec: u64) -> SessionId {
        SessionId::new(
            ProtocolType::B2A,
            SessionId::pack_slot(exec, 0, 0),
            self.instance_id,
        )
    }

    /// Runs one A2B batch on every party and returns the bit shares, indexed
    /// `[party][value][bit]`.
    async fn a2b(
        &self,
        exec: u64,
        inputs: Vec<Vec<RobustShare<F>>>,
        edabits: Vec<Vec<EdaBit<F, K>>>,
        triples: Vec<Vec<GfBeaverTriple<K>>>,
    ) -> Vec<Vec<Vec<GfShare<K>>>> {
        let session_id = self.a2b_session(exec);
        let mut handles = Vec::with_capacity(self.n_parties);
        for party in 0..self.n_parties {
            let mut node = self.a2b[party].clone();
            let net = self.network[party].clone();
            let x = inputs[party].clone();
            let edabits = edabits[party].clone();
            let triples = triples[party].clone();
            handles.push(tokio::spawn(async move {
                node.init(session_id, x, edabits, triples, TIMEOUT, net)
                    .await
                    .unwrap_or_else(|e| panic!("A2B init failed on party {party}: {e:?}"));
                let bits = node
                    .wait_for_result(session_id, TIMEOUT)
                    .await
                    .unwrap_or_else(|e| panic!("A2B result missing on party {party}: {e:?}"));
                assert!(
                    node.clear_store(session_id).await,
                    "A2B session was not retired on party {party}"
                );
                bits
            }));
        }

        let mut results = Vec::with_capacity(self.n_parties);
        for handle in handles {
            results.push(handle.await.expect("A2B task panicked"));
        }
        results
    }

    /// Runs one B2A batch on every party and returns the arithmetic shares, indexed
    /// `[party][value]`. `full_width` selects `b2a_full_width_unchecked` over `b2a`.
    async fn b2a(
        &self,
        exec: u64,
        bits: Vec<Vec<Vec<GfShare<K>>>>,
        dabits: Vec<Vec<DaBit<F, K>>>,
        full_width: bool,
    ) -> Vec<Vec<RobustShare<F>>> {
        let session_id = self.b2a_session(exec);
        let mut handles = Vec::with_capacity(self.n_parties);
        for party in 0..self.n_parties {
            let mut node = self.b2a[party].clone();
            let net = self.network[party].clone();
            let bits = bits[party].clone();
            let dabits = dabits[party].clone();
            handles.push(tokio::spawn(async move {
                let started = if full_width {
                    node.b2a_full_width_unchecked(session_id, bits, dabits, TIMEOUT, net)
                        .await
                } else {
                    node.b2a(session_id, bits, dabits, TIMEOUT, net).await
                };
                started.unwrap_or_else(|e| panic!("B2A init failed on party {party}: {e:?}"));
                let values = node
                    .wait_for_result(session_id, TIMEOUT)
                    .await
                    .unwrap_or_else(|e| panic!("B2A result missing on party {party}: {e:?}"));
                assert!(
                    node.clear_store(session_id).await,
                    "B2A session was not retired on party {party}"
                );
                values
            }));
        }

        let mut results = Vec::with_capacity(self.n_parties);
        for handle in handles {
            results.push(handle.await.expect("B2A task panicked"));
        }
        results
    }
}

/// Checks one A2B batch's output against the canonical bit decomposition of every input.
///
/// Asserts three separate things, because two of them can hold while the third fails: that every
/// bit share is well formed (degree `t`, this party's index), that each bit reconstructs to the
/// right bit from a *quorum*, and that the recomposition of the whole 64-bit vector is the input
/// as an integer — the last is what catches a decomposition that is right bit by bit against a
/// wrong expectation.
fn assert_a2b_matches(
    label: &str,
    values: &[F],
    results: &[Vec<Vec<GfShare<K>>>],
    n_parties: usize,
    t: usize,
) {
    let width = field_bit_width::<F>();
    for (party, per_value) in results.iter().enumerate() {
        assert_eq!(
            per_value.len(),
            values.len(),
            "{label}: party {party} returned the wrong number of conversions"
        );
        for bits in per_value {
            assert_eq!(bits.len(), width, "{label}: wrong output width");
            for bit in bits {
                assert_eq!(bit.degree, t, "{label}: output share is not degree t");
                assert_eq!(
                    bit.id, party,
                    "{label}: output share carries a foreign index"
                );
            }
        }
    }

    for (index, value) in values.iter().enumerate() {
        let want = expected_bits(*value);
        let mut got = Vec::with_capacity(width);
        for bit in 0..width {
            let column: Vec<GfShare<K>> = results
                .iter()
                .map(|per_value| per_value[index][bit].clone())
                .collect();
            got.push(recover_bit(&column, n_parties, t));
        }
        assert_eq!(
            got, want,
            "{label}: bit decomposition of value {index} is wrong"
        );

        let mut repr = [0u8; 8];
        repr.copy_from_slice(&value.into_bigint().to_bytes_le()[0..8]);
        assert_eq!(
            recompose_u128(&got),
            u64::from_le_bytes(repr) as u128,
            "{label}: recomposition of value {index} is not the canonical representative"
        );
    }
}

/// Drives one A2B batch end to end from plain field values, dealing everything it needs.
async fn a2b_case(
    label: &str,
    n_parties: usize,
    t: usize,
    instance_id: u32,
    values: &[F],
    seed: u64,
) {
    setup_tracing();
    let harness = ConvHarness::new(n_parties, t, instance_id);
    let mut rng = StdRng::seed_from_u64(seed);

    let per_conversion = A2BNode::<F, K>::gf_triples_per_conversion().unwrap();
    let inputs = deal_field(n_parties, t, values, &mut rng);
    let edabits = deal_edabits(n_parties, t, values.len(), &mut rng);
    let triples = deal_gf_triples(n_parties, t, per_conversion * values.len(), &mut rng);

    let results = harness.a2b(1, inputs, edabits, triples).await;
    assert_a2b_matches(label, values, &results, n_parties, t);
}

